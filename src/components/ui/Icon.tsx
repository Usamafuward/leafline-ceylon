interface DynamicIconProps extends LucideProps {
  name: string;
}

export default function DynamicIcon({
  name,
  className,
  size = 20,
  strokeWidth = 2,
  ...props
}: DynamicIconProps) {
  const IconComponent = ICON_MAP[name.trim().toLowerCase()] || Sparkle;
  return (
    <IconComponent
      size={size}
      strokeWidth={strokeWidth}
      className={className}
      {...props}
    />
  );
}
